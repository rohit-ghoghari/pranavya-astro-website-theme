import { defineCollection } from "astro:content";
import { glob } from "astro/loaders";
import { z } from "zod";

export const classesCollection = defineCollection({
    loader: glob({ pattern: "**/*.md", base: "./src/content/classes" }),
    schema: z.object({
        title: z.string(),
        pageTitle: z.string(),
        pageDescription: z.string(),
        listingTitle: z.string(),
        listingCategory: z.string(),
        listingDescription: z.string(),
        mainImage: z.string(),
        mainImageAlt: z.string(),
        expectTitle: z.string(),
        expectSubtitle: z.string(),
        expectDescription: z.string(),
        classFlowHeading: z.string(),
        classFlowItems: z.array(z.object({
            title: z.string(),
            description: z.string(),
        })),
        experienceTitle: z.string(),
        videoBanner: z.string(),
        videoBannerAlt: z.string(),
        videoSrc: z.string(),
        intensityLevel: z.string(),
        intensityBadgeClass: z.string(),
        category: z.string(),
        filterCategories: z.array(z.string()).default([]),
        overview: z.array(z.object({
            label: z.string(),
            value: z.string(),
        })),
        benefits: z.array(z.string()),
        instructor: z.object({
            name: z.string(),
            bio: z.string(),
            image: z.string(),
            imageAlt: z.string().default("instructor"),
            certifications: z.array(z.string()),
            instagram: z.string().default("https://www.instagram.com/"),
            twitter: z.string().default("https://x.com/?lang=en"),
            facebook: z.string().default("https://www.facebook.com/"),
            youtube: z.string().default("https://www.youtube.com/"),
        }),
        monthlyPlans: z.array(z.object({
            name: z.string(),
            description: z.string(),
            price: z.string(),
            period: z.string(),
            features: z.array(z.string()),
        })),
        yearlyPlans: z.array(z.object({
            name: z.string(),
            description: z.string(),
            price: z.string(),
            period: z.string(),
            features: z.array(z.string()),
        })),
        relatedClasses: z.array(z.object({
            title: z.string(),
            category: z.string(),
            description: z.string(),
            image: z.string(),
            intensity: z.string(),
            intensityBadge: z.string(),
            instructor: z.string(),
            instructorImage: z.string(),
            href: z.string(),
        })),
        metaDescription: z.string().optional(),
    }),
});
